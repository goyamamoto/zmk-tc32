SHIFTS = {"left": [("&kp LSHFT", LSFT)], "right": [("&kp RSHFT", RSFT)],
          "both": [("&kp LSHFT", LSFT), ("&kp RSHFT", RSFT)]}


def shifted_sequence(case, key, in_usage, out_usage, out_mods, shifts, key_first):
    """Shift(s) down, key down, then the key or the Shift(s) up first.
    out_usage/out_mods: what the key reports while held (substituted or not)."""
    held = 0
    for binding, bit in shifts:
        case.press(binding)
        held |= bit
        case.expect(kbd(held))
    case.press(key)
    case.expect(kbd(out_mods, out_usage))
    substituted = out_usage != in_usage
    if key_first:
        case.release(key)
        case.expect(kbd(held))
        for binding, bit in reversed(shifts):
            case.release(binding)
            held &= ~bit
            case.expect(kbd(held))
    else:
        for binding, bit in reversed(shifts):
            case.release(binding)
            held &= ~bit
            # Substituted: the key keeps its own modifiers (spec S03, S14).
            # Identity: the physical Shift that is left.
            case.expect(kbd(out_mods if substituted else held, out_usage))
        case.release(key)
        case.expect(kbd(0))


def table_case():
    keys = ["&kp " + ZMK_NAMES[u] for u in ZMK_NAMES]
    bindings = ["&kp LSHFT", "&kp RSHFT"] + keys + [
        "&kp N1", "&kp PLUS", "&kp LC(EQUAL)", "&kp F24", "&usjis USJIS_TOG"]
    case = Case("usjis-table", ["CONFIG_ZMK_USJIS_DEFAULT_ENABLED=y",
                                "CONFIG_ZMK_USJIS_LAYER_MASK=0"], bindings)
    case.expect("listener order ok")

    def run_table(enabled):
        for cid, in_usage, in_shift, out_usage, out_shift in TABLE:
            key = "&kp " + ZMK_NAMES[in_usage]
            if enabled:
                usage, mods = out_usage, LSFT if out_shift else 0
            if in_shift:
                for variant in ("left", "right", "both"):
                    for key_first in (True, False):
                        if not enabled:
                            usage = in_usage
                            mods = sum(bit for _, bit in SHIFTS[variant])
                        shifted_sequence(case, key, in_usage, usage, mods, SHIFTS[variant],
                                         key_first)
            else:
                case.tap(key)
                case.expect(kbd(mods, usage) if enabled else kbd(0, in_usage), kbd(0))
            case.separator()

    # C01-C20 with the mode enabled.
    run_table(True)
    # Chords outside the table stay identity (spec section 5).
    for usage in (N2, N6, N7, N8, N9, N0, MINUS, SEMI):
        case.tap("&kp " + ZMK_NAMES[usage])
        case.expect(kbd(0, usage), kbd(0))
    shifted_sequence(case, "&kp N1", N1, N1, RSFT, SHIFTS["right"], True)
    case.separator()
    # Shift from the key's own binding matches (&kp PLUS = LS(EQUAL) is C10);
    # Ctrl is kept (LC(EQUAL) is C09 plus Ctrl).
    case.tap("&kp PLUS")
    case.expect(kbd(LSFT, SEMI), kbd(0))
    case.tap("&kp LC(EQUAL)")
    case.expect(kbd(LCTL | LSFT, MINUS), kbd(0))
    case.separator()
    # S01: disabled, every chord is identity.
    case.tap("&usjis USJIS_TOG")
    case.expect("mode DISABLED")
    run_table(False)
    case.tap("&kp PLUS")
    case.expect(kbd(LSFT, EQUAL), kbd(0))
    case.tap("&kp LC(EQUAL)")
    case.expect(kbd(LCTL, EQUAL), kbd(0))
    return case


