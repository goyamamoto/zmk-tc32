LAYERS_KEYMAP = """    behaviors {
        ime_ht: ime_hold_tap {
            compatible = "zmk,behavior-hold-tap";
            #binding-cells = <2>;
            flavor = "hold-preferred";
            tapping-term-ms = <200>;
            bindings = <&kp>, <&kp>;
        };
    };

    /* The B1 Pro's layers: 0 Mac, 1 Mac Fn, 2 Win (held by the OS switch),
     * 3 Win Fn. Fn+Tab toggles the mode, which applies in Win only. */
    keymap {
        compatible = "zmk,keymap";
        mac {
            bindings = <&kp EQUAL &mo 1 &kp TAB &mo 2 &ime_ht LALT INT5 &kp RSHFT &kp N2 &kp F24>;
        };
        mac_fn {
            bindings = <&trans &trans &usjis USJIS_TOG &trans &trans &trans &trans &trans>;
        };
        win {
            bindings = <&trans &mo 3 &trans &trans &trans &trans &trans &trans>;
        };
        win_fn {
            bindings = <&trans &trans &usjis USJIS_TOG &trans &trans &trans &trans &trans>;
        };
    };"""


def layers_case():
    # The mask is the kb1 default (0x04); zmk-tc32 defaults to 0, so it is set
    # explicitly here for both copies.
    c = Case("usjis-layers", ["CONFIG_ZMK_USJIS_LAYER_MASK=0x04"], keymap=LAYERS_KEYMAP, columns=8)
    EQ, FN, TAB, WIN, IME, RS, TWO, SEP = range(8)
    c.expect("listener order ok")
    # Disabled by default (no stored setting).
    c.tap(EQ)
    c.expect(kbd(0, EQUAL), kbd(0))
    # Mac Fn+Tab enables the mode; Mac stays identity (layer mask 0x04).
    c.press(FN); c.tap(TAB); c.release(FN)
    c.expect("mode ENABLED")
    c.tap(EQ)
    c.expect(kbd(0, EQUAL), kbd(0))
    # The Win position (&mo 2 held) substitutes.
    c.press(WIN)
    c.tap(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(0))
    c.press(RS); c.tap(TWO); c.release(RS)
    c.expect(kbd(RSFT), kbd(0, JIS_AT), kbd(RSFT), kbd(0))
    # The IME hold-tap held as Alt: Alt is kept on a substituted key.
    c.press(IME); c.tap(EQ); c.release(IME)
    c.expect(kbd(LALT), kbd(LALT | LSFT, MINUS), kbd(LALT), kbd(0))
    # Tapped, it sends Muhenkan (INT5), not substituted.
    c.tap(IME)
    c.expect(kbd(0, INT5), kbd(0))
    c.tap(SEP)
    c.expect(kbd(0, F24), kbd(0))
    # Win Fn+Tab disables it.
    c.press(FN); c.tap(TAB); c.release(FN)
    c.expect("mode DISABLED")
    c.tap(EQ)
    c.expect(kbd(0, EQUAL), kbd(0))
    c.release(WIN)
    return c


