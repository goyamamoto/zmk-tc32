def scenarios_case():
    bindings = ["&kp RSHFT", "&kp N2", "&kp MINUS", "&kp A", "&kp EQUAL", "&usjis USJIS_TOG",
                "&usjis USJIS_ON", "&usjis USJIS_OFF", "&kp LS(A)", "&kp LC(X)", "&kp LALT",
                "&kp C_VOL_UP", "&kp F24", "&test_clear"]
    c = Case("usjis-scenarios", ["CONFIG_ZMK_USJIS_DEFAULT_ENABLED=y",
                                 "CONFIG_ZMK_USJIS_LAYER_MASK=0"], bindings)
    RS, TWO, MIN, KA, EQ = "&kp RSHFT", "&kp N2", "&kp MINUS", "&kp A", "&kp EQUAL"
    TOG, ON, OFF = "&usjis USJIS_TOG", "&usjis USJIS_ON", "&usjis USJIS_OFF"
    c.expect("listener order ok")

    # S02
    c.press(RS); c.press(TWO); c.release(TWO); c.release(RS)
    c.expect(kbd(RSFT), kbd(0, JIS_AT), kbd(RSFT), kbd(0))
    c.separator()
    # S03
    c.press(RS); c.press(TWO); c.release(RS); c.release(TWO)
    c.expect(kbd(RSFT), kbd(0, JIS_AT), kbd(0, JIS_AT), kbd(0))
    c.separator()
    # S05
    c.press(RS); c.press(TWO); c.press(MIN); c.release(MIN); c.release(TWO); c.release(RS)
    c.expect(kbd(RSFT), kbd(0, JIS_AT), kbd(LSFT, JIS_AT, JIS_RO), kbd(0, JIS_AT), kbd(RSFT),
             kbd(0))
    c.separator()
    # S06: a held substituted key sends nothing more during one second.
    c.press(EQ, wait=1000); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(0))
    c.separator()
    # S07 (enabled): a consumer usage is unchanged.
    c.tap("&kp C_VOL_UP")
    c.expect(consumer(C_VOL_UP), consumer())
    c.separator()
    # S11
    c.press(RS); c.press(TWO); c.press(KA); c.release(KA); c.release(TWO); c.release(RS)
    c.expect(kbd(RSFT), kbd(0, JIS_AT), kbd(RSFT, A, JIS_AT), kbd(0, JIS_AT), kbd(RSFT), kbd(0))
    c.separator()
    # S12
    c.press(EQ); c.press(KA); c.release(KA); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(0, A, MINUS), kbd(LSFT, MINUS), kbd(0))
    c.separator()
    # S13
    c.press(EQ); c.press(RS); c.press(TWO); c.release(TWO); c.release(RS); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(LSFT, MINUS), kbd(0, MINUS, JIS_AT), kbd(LSFT, MINUS),
             kbd(LSFT, MINUS), kbd(0))
    c.separator()
    # S14
    c.press(RS); c.press(MIN); c.release(RS); c.release(MIN)
    c.expect(kbd(RSFT), kbd(LSFT, JIS_RO), kbd(LSFT, JIS_RO), kbd(0))
    c.separator()
    # S18: the Shift of LS(A) is not restored after C09 is released.
    c.press("&kp LS(A)"); c.press(EQ); c.release(EQ); c.release("&kp LS(A)")
    c.expect(kbd(LSFT, A), kbd(LSFT, A, MINUS), kbd(0, A), kbd(0))
    c.separator()
    # S19: no keyboard report loses the added Shift of C09 while it is held.
    c.press(KA); c.press(EQ); c.release(KA)
    c.tap("&kp C_VOL_UP")
    c.release(EQ)
    c.expect(kbd(0, A), kbd(LSFT, A, MINUS), kbd(LSFT, MINUS), consumer(C_VOL_UP), consumer(),
             kbd(0))
    c.separator()
    # S20: the Ctrl of LC(X) is not restored once removed, not even by Alt.
    c.press(EQ); c.press("&kp LC(X)"); c.press(KA); c.release(KA)
    c.press("&kp LALT"); c.release("&kp LALT"); c.release("&kp LC(X)"); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(LCTL, X, MINUS), kbd(0, A, X, MINUS), kbd(0, X, MINUS),
             kbd(LALT, X, MINUS), kbd(0, X, MINUS), kbd(LSFT, MINUS), kbd(0))
    c.separator()
    # S17: the endpoint changes (the switch moves between BT and cable) while
    # C09 is held. Nothing after it carries C09's usage or Shift, its release
    # sends nothing, and no press record is left: a toggle applies at once.
    c.press(EQ); c.tap("&test_clear"); c.press(RS); c.tap(KA); c.release(RS); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), "endpoint clear", "HID state cleared by endpoint switch",
             kbd(RSFT), kbd(RSFT, A), kbd(RSFT), kbd(0))
    c.tap(TOG)
    c.expect("mode DISABLED")
    c.tap(TOG)
    c.expect("mode ENABLED")
    c.tap(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(0))
    c.separator()
    # S04 and S08: OFF while C09 is held is applied after its release; the
    # mode keys send nothing.
    c.press(EQ); c.tap(OFF); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), "mode request DISABLED pending", kbd(0), "applying pending mode",
             "mode DISABLED")
    c.tap(EQ)
    c.expect(kbd(0, EQUAL), kbd(0))
    # S07 (disabled)
    c.tap("&kp C_VOL_UP")
    c.expect(consumer(C_VOL_UP), consumer())
    c.separator()
    # S15. The release of A is not substituted: the pending mode is applied
    # before hid_listener reports the release.
    c.press(KA); c.tap(ON); c.press(RS); c.tap(TWO); c.release(KA); c.tap(TWO); c.release(RS)
    c.expect(kbd(0, A), "mode request ENABLED pending", kbd(RSFT, A), kbd(RSFT, A, N2),
             kbd(RSFT, A), "applying pending mode", "mode ENABLED", kbd(RSFT), kbd(0, JIS_AT),
             kbd(RSFT), kbd(0))
    c.separator()
    # S16: two toggles while C09 is held cancel each other.
    c.press(EQ); c.tap(TOG); c.tap(TOG); c.release(EQ)
    c.expect(kbd(LSFT, MINUS), "mode request DISABLED pending", "mode request ENABLED pending",
             kbd(0))
    c.tap(EQ)
    c.expect(kbd(LSFT, MINUS), kbd(0))
    # ON while enabled and OFF while disabled change nothing (spec section 3).
    c.tap(ON)
    c.tap(TOG)
    c.expect("mode DISABLED")
    c.tap(OFF)
    c.tap(TOG)
    c.expect("mode ENABLED")
    c.separator()
    return c


